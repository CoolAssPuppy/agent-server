export function renderEnvironmentReferenceTable(): string {
  const rows = ENVIRONMENT_VARIABLE_REFERENCE.map(({ name, defaultValue, description }) => {
    const renderedDefault = defaultValue === 'generated by `agent-server init`'
      ? defaultValue
      : defaultValue ? `\`${defaultValue}\`` : '';
    return `| \`${name}\` | ${renderedDefault} | ${description} |`;
  });
  return [
    '| Variable | Default | Description |',
    '|---|---|---|',
    ...rows,
  ].join('\n');
}
